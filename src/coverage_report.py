"""Report which baseline controls the example detections support.

A detection "supports" a control when it produces evidence or monitoring that an
assessor could use for that control. It never fully satisfies a control on its
own: policy, procedure, and configuration still matter. Coverage is counted by
exact control id, so a detection mapped to AC-2(4) does not count toward AC-2.

Examples:
    python -m src.coverage_report --baseline moderate
    python -m src.coverage_report --baseline high --output report.md
"""

from __future__ import annotations

import argparse
from collections import defaultdict
from dataclasses import dataclass, field
from pathlib import Path

from src.baseline_selector import select, sort_key
from src.loaders import BASELINES, Control, load_controls, load_crosswalk, load_detections


@dataclass
class Coverage:
    baseline: str
    baseline_total: int
    covered: dict[str, list[str]]  # control -> detections, only controls in the baseline
    outside_baseline: dict[str, list[str]]  # mapped controls not selected in this baseline
    by_family: dict[str, tuple[int, int]]  # family -> (covered, total), families with coverage only
    req_171: dict[str, list[str]] = field(default_factory=dict)  # 171 req -> supported source controls
    req_171_total: int = 0

    @property
    def percent(self) -> float:
        return 100.0 * len(self.covered) / self.baseline_total if self.baseline_total else 0.0


def build_coverage(
    controls: dict[str, Control],
    detections: list[dict],
    crosswalk: list[dict],
    baseline: str,
) -> Coverage:
    in_baseline = select(controls, baseline)
    baseline_ids = {c.control_id for c in in_baseline}

    mapped: dict[str, set[str]] = defaultdict(set)
    for row in detections:
        if row["control_53"] not in controls:
            raise ValueError(f"Detection {row['detection']!r} maps to unknown control {row['control_53']}")
        mapped[row["control_53"]].add(row["detection"])

    covered = {cid: sorted(d) for cid, d in mapped.items() if cid in baseline_ids}
    outside = {cid: sorted(d) for cid, d in mapped.items() if cid not in baseline_ids}

    totals = defaultdict(int)
    for c in in_baseline:
        totals[c.family] += 1
    hits = defaultdict(int)
    for cid in covered:
        hits[controls[cid].family] += 1
    by_family = {fam: (hits[fam], totals[fam]) for fam in sorted(hits)}

    req_171: dict[str, list[str]] = defaultdict(list)
    for row in crosswalk:
        if row["control_53"] in mapped:
            req_171[row["req_171"]].append(row["control_53"])

    return Coverage(
        baseline=baseline,
        baseline_total=len(baseline_ids),
        covered=dict(sorted(covered.items(), key=lambda kv: sort_key(kv[0]))),
        outside_baseline=dict(sorted(outside.items(), key=lambda kv: sort_key(kv[0]))),
        by_family=by_family,
        req_171={k: sorted(set(v), key=sort_key) for k, v in sorted(req_171.items())},
        req_171_total=len({row["req_171"] for row in crosswalk}),
    )


def render_markdown(cov: Coverage, controls: dict[str, Control]) -> str:
    lines = [
        f"# Detection coverage: SP 800-53 Rev. 5 {cov.baseline.title()} baseline",
        "",
        "_Generated by `src/coverage_report.py`. Personal study material, not an assessment._",
        "",
        f"- Controls in baseline: **{cov.baseline_total}**",
        f"- Controls supported by at least one detection: **{len(cov.covered)}** ({cov.percent:.1f}%)",
        f"- 800-171r3 requirements touched through the crosswalk: "
        f"**{len(cov.req_171)}** of {cov.req_171_total}",
        "",
        "Low percentages are expected. Most controls are policy, process, or",
        "configuration controls that a SIEM search cannot evidence on its own.",
        "",
        "## Supported controls",
        "",
        "| Control | Title | Detections |",
        "|---|---|---|",
    ]
    for cid, dets in cov.covered.items():
        lines.append(f"| {cid} | {controls[cid].title} | {', '.join(dets)} |")

    lines += ["", "## Coverage by family", "", "| Family | Supported | In baseline |", "|---|---|---|"]
    for fam, (hit, total) in cov.by_family.items():
        lines.append(f"| {fam} | {hit} | {total} |")

    if cov.outside_baseline:
        lines += [
            "",
            "## Mapped controls not selected in this baseline",
            "",
            "These detections still add value, but the baseline does not require the control.",
            "",
        ]
        for cid, dets in cov.outside_baseline.items():
            lines.append(f"- {cid} {controls[cid].title}: {', '.join(dets)}")

    lines += ["", "## 800-171r3 requirements touched", "", "| Requirement | Supported source controls |", "|---|---|"]
    for req, cids in cov.req_171.items():
        lines.append(f"| {req} | {', '.join(cids)} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--baseline", choices=BASELINES, default="moderate")
    p.add_argument("--output", type=Path, help="Write Markdown here instead of stdout.")
    args = p.parse_args(argv)

    controls = load_controls()
    cov = build_coverage(controls, load_detections(), load_crosswalk(), args.baseline)
    report = render_markdown(cov, controls)
    if args.output:
        args.output.write_text(report)
        print(f"Wrote {args.output}")
    else:
        print(report, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
